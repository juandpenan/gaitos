"""Make the MuJoCo model (MJCF) of a robot from its physics URDF (the make_gazebo_urdf.py
variant: primitive collisions, no mimic) and a small spec (YAML).

    make_mjcf.py <robot_gazebo.urdf> <spec.yaml> <robot.xml> [--meshes <obj folder>]

The URDF is compiled by MuJoCo itself (`mujoco-compile`, or MUJOCO_COMPILE), then completed
with what the URDF does not say:

  base: base_link          # root body: gets the free joint
  imu: {body: torso, pos: [x, y, z]}   # site `imu` with the sensors imu_quat, imu_gyro, imu_acc
  timestep: 0.001
  joint: {armature: 0.003, damping: 0.05, frictionloss: 0.03}   # every hinge
  geom: {friction: [1.0, 0.02, 0.01], condim: 3}
  actuators: true          # a motor per hinge, ctrlrange = +-effort of the URDF limit
  skeleton: {radius: 0.012, rgba: [0.85, 0.85, 0.9, 1]}   # visual capsules body -> child
                           # (no contact, no mass): the looks without meshes
  meshes:                  # the visual meshes of the URDF, as OBJ (dae_to_obj.py)
    meshdir: meshes        # where the model finds them, relative to <robot.xml>
    texture: ../materials/texture/robot.png   # optional, relative to <robot.xml>

Without `meshes` the visuals of the URDF are left out. With it, every <visual> mesh of the URDF
becomes a geom (no contact, no mass, group 1) with the mesh <name>.obj of the same name, taken
from --meshes when compiling (default: meshdir next to <robot.xml>), and the collision geoms go
to group 3 (hidden by default).

Writes <robot.xml> and, next to it, scene.xml (flat ground) that includes it.
"""
import os
import shutil
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET

import yaml


def vec(v):
    return ' '.join(str(float(x)) for x in v)


SCENE = """<!-- gaitos: flat ground scene for the {name} model (generated by make_mjcf.py) -->
<mujoco model="{name} scene">
  <include file="{file}"/>

  <statistic center="0 0 0.3" extent="1.0"/>

  <visual>
    <headlight diffuse="0.6 0.6 0.6" ambient="0.3 0.3 0.3" specular="0 0 0"/>
    <rgba haze="0.15 0.25 0.35 1"/>
    <global azimuth="-130" elevation="-20" offwidth="1280" offheight="720"/>
  </visual>

  <asset>
    <texture type="skybox" builtin="gradient" rgb1="0.3 0.5 0.7" rgb2="0 0 0" width="512" height="3072"/>
    <texture type="2d" name="groundplane" builtin="checker" mark="edge" rgb1="0.2 0.3 0.4"
      rgb2="0.1 0.2 0.3" markrgb="0.8 0.8 0.8" width="300" height="300"/>
    <material name="groundplane" texture="groundplane" texuniform="true" texrepeat="5 5"
      reflectance="0.2"/>
  </asset>

  <worldbody>
    <light pos="0 0 3.5" dir="0 0 -1" directional="true"/>
    <geom name="floor" size="0 0 0.05" type="plane" material="groundplane" friction="1 0.02 0.01"/>
  </worldbody>
</mujoco>
"""


def main():
    args = sys.argv[1:]
    mesh_path = None
    if '--meshes' in args:
        i = args.index('--meshes')
        mesh_path = os.path.abspath(args[i + 1])
        del args[i:i + 2]
    if len(args) != 3:
        sys.exit(__doc__)
    src, spec_file, dst = args
    spec = yaml.safe_load(open(spec_file)) or {}
    meshes = spec.get('meshes')
    if meshes:
        meshdir = meshes.get('meshdir', 'meshes')
        mesh_path = mesh_path or os.path.join(os.path.dirname(os.path.abspath(dst)), meshdir)
    compiler = os.environ.get('MUJOCO_COMPILE') or shutil.which('mujoco-compile') or shutil.which('compile')
    if not compiler:
        sys.exit('mujoco-compile not found (set MUJOCO_COMPILE)')

    # URDF without visuals, with the MuJoCo compiler options
    tree = ET.parse(src)
    robot = tree.getroot()
    name = robot.get('name', 'robot')
    visual_meshes = set()
    for link in robot.findall('link'):
        for v in link.findall('visual'):
            m = v.find('geometry/mesh')
            if not meshes or m is None:
                link.remove(v)
                continue
            # MuJoCo keeps only the file name of the URDF mesh, found in meshdir
            stem = os.path.splitext(os.path.basename(m.get('filename')))[0]
            if not os.path.isfile(os.path.join(mesh_path, stem + '.obj')):
                sys.exit(f'{stem}.obj not in {mesh_path} (dae_to_obj.py, --meshes)')
            m.set('filename', stem + '.obj')
            visual_meshes.add(stem)
    for g in robot.findall('gazebo'):
        robot.remove(g)
    for m in robot.findall('mujoco'):
        robot.remove(m)
    # Free floating base: a floating joint from a world link (MuJoCo makes it a free joint;
    # without it the fixed root would be fused with the world)
    base_name = spec.get('base', 'base_link')
    if robot.find(f"link[@name='{base_name}']") is None:
        sys.exit(f'base link {base_name} not in the URDF')
    ET.SubElement(robot, 'link', {'name': 'world'})
    fj = ET.SubElement(robot, 'joint', {'name': 'root', 'type': 'floating'})
    ET.SubElement(fj, 'parent', {'link': 'world'})
    ET.SubElement(fj, 'child', {'link': base_name})
    mj = ET.SubElement(robot, 'mujoco')
    compiler_opts = {'discardvisual': 'false' if meshes else 'true', 'balanceinertia': 'true',
                     'fusestatic': 'true', 'angle': 'radian'}
    if meshes:
        compiler_opts['meshdir'] = mesh_path
    ET.SubElement(mj, 'compiler', compiler_opts)
    limits = {}
    for j in robot.findall('joint'):
        lim = j.find('limit')
        if j.get('type') in ('revolute', 'continuous') and lim is not None:
            limits[j.get('name')] = float(lim.get('effort', 0.0))

    with tempfile.TemporaryDirectory() as tmp:
        urdf = os.path.join(tmp, f'{name}.urdf')
        tree.write(urdf, encoding='utf-8', xml_declaration=True)
        raw = os.path.join(tmp, f'{name}.xml')
        subprocess.run([compiler, urdf, raw], check=True, stdout=subprocess.DEVNULL)
        mjcf = ET.parse(raw)
    root = mjcf.getroot()
    root.set('model', name)

    # Options and defaults
    for tag in ('option', 'default'):
        for e in root.findall(tag):
            root.remove(e)
    opt = ET.Element('option', {'timestep': str(float(spec.get('timestep', 0.001))),
                                'integrator': 'implicitfast'})
    root.insert(1, opt)
    default = ET.Element('default')
    jd = {k: str(float(v)) for k, v in (spec.get('joint', {}) or {}).items()}
    if jd:
        ET.SubElement(default, 'joint', jd)
    gd = spec.get('geom', {}) or {}
    geom_attrs = {}
    if 'friction' in gd:
        geom_attrs['friction'] = vec(gd['friction'])
    if 'condim' in gd:
        geom_attrs['condim'] = str(int(gd['condim']))
    if geom_attrs:
        ET.SubElement(default, 'geom', geom_attrs)
    root.insert(2, default)

    # Free floating base and IMU site
    world = root.find('worldbody')
    bodies = {b.get('name'): b for b in world.iter('body')}
    base = bodies.get(spec.get('base', 'base_link'))
    if base is None:
        sys.exit(f"base body {spec.get('base')} not in the model: {sorted(bodies)}")
    if base.find('freejoint') is None and base.find("joint[@type='free']") is None:
        sys.exit(f'{base.get("name")} has no free joint')
    imu = spec.get('imu')
    if imu:
        body = bodies.get(imu.get('body', spec.get('base')))
        if body is None:
            sys.exit(f"imu body {imu.get('body')} not in the model")
        ET.SubElement(body, 'site', {'name': 'imu', 'pos': vec(imu.get('pos', [0, 0, 0]))})

    # Visual meshes: looks only, with the texture of the robot
    if meshes:
        comp = root.find('compiler')
        comp.set('meshdir', meshdir)
        asset = root.find('asset')
        for m in asset.findall('mesh'):
            m.set('file', os.path.basename(m.get('file')))
        material = None
        if meshes.get('texture'):
            comp.set('texturedir', os.path.dirname(meshes['texture']) or '.')
            ET.SubElement(asset, 'texture', {'name': f'{name}_texture', 'type': '2d',
                                             'file': os.path.basename(meshes['texture'])})
            material = f'{name}_material'
            ET.SubElement(asset, 'material', {'name': material, 'texture': f'{name}_texture',
                                              'specular': '0.3', 'shininess': '0.3'})
        n = 0
        for g in world.iter('geom'):
            if g.get('type') != 'mesh':
                g.set('group', '3')   # collision primitives: hidden by default under the meshes
                continue
            for k in ('contype', 'conaffinity', 'density'):
                g.attrib.pop(k, None)
            for k in ('rgba', 'group'):
                g.attrib.pop(k, None)
            g.set('class', 'visual')
            if material:
                g.set('material', material)
            n += 1
        if n < len(visual_meshes):
            sys.exit(f'{n} visual geoms in the model, {len(visual_meshes)} meshes in the URDF')
        vis = ET.SubElement(default, 'default', {'class': 'visual'})
        ET.SubElement(vis, 'geom', {'contype': '0', 'conaffinity': '0', 'group': '1',
                                    'mass': '0'})

    # Visual skeleton: a capsule from each body to each child body (looks only)
    skel = spec.get('skeleton')
    if skel:
        radius = float(skel.get('radius', 0.012))
        rgba = vec(skel.get('rgba', [0.85, 0.85, 0.9, 1.0]))
        for body in world.iter('body'):
            for child in body.findall('body'):
                pos = [float(x) for x in child.get('pos', '0 0 0').split()]
                if sum(x * x for x in pos) < (0.5 * radius) ** 2:
                    continue
                ET.SubElement(body, 'geom', {
                    'name': f"{child.get('name')}_bone", 'type': 'capsule',
                    'fromto': f"0 0 0 {vec(pos)}", 'size': str(radius), 'rgba': rgba,
                    'contype': '0', 'conaffinity': '0', 'group': '1', 'mass': '0'})

    # Motors with the torque limits of the URDF
    for e in root.findall('actuator'):
        root.remove(e)
    if spec.get('actuators', True):
        act = ET.SubElement(root, 'actuator')
        for j in world.iter('joint'):
            jn = j.get('name')
            if j.get('type', 'hinge') != 'hinge' or jn not in limits:
                continue
            attrs = {'name': jn, 'joint': jn}
            if limits[jn] > 0.0:
                attrs.update({'ctrllimited': 'true', 'ctrlrange': f'{-limits[jn]} {limits[jn]}'})
            ET.SubElement(act, 'motor', attrs)

    # IMU sensors (names expected by gaitos_mujoco MujocoHardware)
    for e in root.findall('sensor'):
        root.remove(e)
    if imu:
        sen = ET.SubElement(root, 'sensor')
        ET.SubElement(sen, 'framequat', {'name': 'imu_quat', 'objtype': 'site', 'objname': 'imu'})
        ET.SubElement(sen, 'gyro', {'name': 'imu_gyro', 'site': 'imu'})
        ET.SubElement(sen, 'accelerometer', {'name': 'imu_acc', 'site': 'imu'})

    root.insert(0, ET.Comment(f' Generated by make_mjcf.py from {os.path.basename(src)} and '
                              f'{os.path.basename(spec_file)}: do not edit '))
    ET.indent(mjcf, space='  ')
    mjcf.write(dst, encoding='utf-8')
    scene = os.path.join(os.path.dirname(dst), 'scene.xml')
    with open(scene, 'w') as f:
        f.write(SCENE.format(name=name, file=os.path.basename(dst)))
    print(f'{dst} and {scene} written')


if __name__ == '__main__':
    main()
